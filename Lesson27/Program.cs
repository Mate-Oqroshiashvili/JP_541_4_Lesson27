using System.Diagnostics;

Console.OutputEncoding = System.Text.Encoding.UTF8;

// =====================================================================
// იდეა: საუზმეს ვამზადებთ — ჩაი, ტოსტი და კვერცხი.
// ცხოვრებაში ჩაიდანს ჩავრთავთ და სანამ ადუღდება, ტოსტს ვაკეთებთ.
// ჩაიდანთან დგომა და ლოდინი არ გვჭირდება. ზუსტად ესაა ასინქრონულობა.
// =====================================================================


// ---------------------------------------------------------------------
// 1. სინქრონული ვერსია: ყველაფერი რიგრიგობით
// ---------------------------------------------------------------------
Console.WriteLine("===== სინქრონული საუზმე =====");
Stopwatch stopwatch = Stopwatch.StartNew();   // დროის ათვლა იწყება

BoilWater();   // 3 წამი — სანამ არ დასრულდება, შემდეგ ხაზზე ვერ გადავალთ
MakeToast();   // 2 წამი — იწყება მხოლოდ წყლის ადუღების შემდეგ
FryEgg();      // 2 წამი — იწყება მხოლოდ ტოსტის შემდეგ

Console.WriteLine($"საუზმე მზადაა: {stopwatch.Elapsed.TotalSeconds:F0} წამი\n");   // ≈ 7 წამი


// ---------------------------------------------------------------------
// 2. ასინქრონული ვერსია: ყველაფერს ერთად ვიწყებთ
// ---------------------------------------------------------------------
Console.WriteLine("===== ასინქრონული საუზმე =====");
stopwatch.Restart();

// მეთოდის გამოძახება Task-ს მაშინვე უშვებს, მაგრამ მის დასრულებას არ ველოდებით.
// Task არის „დაპირება“: სამუშაო მიმდინარეობს და ოდესმე დასრულდება.
Task waterTask = BoilWaterAsync();
Task toastTask = MakeToastAsync();
Task eggTask = FryEggAsync();

// ეს ხაზი მაშინვე სრულდება. სამივე Task ამ დროს ფონზე მუშაობს.
Console.WriteLine("ყველაფერი დაწყებულია, ამ დროს მაგიდას ვაწყობ...");

// await — „დაელოდე, სანამ დასრულდება“.
// Task.WhenAll — ველოდებით სამივეს ერთად.
await Task.WhenAll(waterTask, toastTask, eggTask);

Console.WriteLine($"საუზმე მზადაა: {stopwatch.Elapsed.TotalSeconds:F0} წამი\n");   // ≈ 3 წამი (ყველაზე გრძელი ოპერაცია)


// ---------------------------------------------------------------------
// 3. Task<T>: ასინქრონული მეთოდი, რომელიც შედეგს აბრუნებს
// ---------------------------------------------------------------------
Console.WriteLine("===== შედეგის დაბრუნება =====");

// await Task<int>-დან int-ს „ამოიღებს“, როცა Task დასრულდება
int cups = await PourTeaAsync();
Console.WriteLine($"ჩამოსხმულია {cups} ჭიქა ჩაი");


// =====================================================================
// სინქრონული მეთოდები
// Thread.Sleep — ნაკადს აჩერებს. ის ამ დროს ვერაფერს აკეთებს, უბრალოდ „სძინავს“.
// =====================================================================

void BoilWater()
{
    Console.WriteLine("წყლის ადუღება დაიწყო...");
    Thread.Sleep(3000);
    Console.WriteLine("  წყალი ადუღდა");
}

void MakeToast()
{
    Console.WriteLine("ტოსტის მომზადება დაიწყო...");
    Thread.Sleep(2000);
    Console.WriteLine("  ტოსტი მზადაა");
}

void FryEgg()
{
    Console.WriteLine("კვერცხის შეწვა დაიწყო...");
    Thread.Sleep(2000);
    Console.WriteLine("  კვერცხი მზადაა");
}


// =====================================================================
// ასინქრონული მეთოდები
// async — მეთოდის შიგნით await-ის გამოყენების ნებას გვაძლევს.
// Task  — დასაბრუნებელი ტიპი (void-ის ასინქრონული „ანალოგი“).
// Async — სახელის ბოლოს იწერება შეთანხმებით, რომ გამომძახებელმა იცოდეს: ეს მეთოდი await-ს საჭიროებს.
// Task.Delay — ელოდება, მაგრამ ნაკადს არ ბლოკავს: ნაკადი ამ დროს სხვა სამუშაოს ასრულებს.
// =====================================================================

async Task BoilWaterAsync()
{
    Console.WriteLine("წყლის ადუღება დაიწყო...");
    await Task.Delay(3000);
    Console.WriteLine("  წყალი ადუღდა");
}

async Task MakeToastAsync()
{
    Console.WriteLine("ტოსტის მომზადება დაიწყო...");
    await Task.Delay(2000);
    Console.WriteLine("  ტოსტი მზადაა");
}

async Task FryEggAsync()
{
    Console.WriteLine("კვერცხის შეწვა დაიწყო...");
    await Task.Delay(2000);
    Console.WriteLine("  კვერცხი მზადაა");
}

// Task<int> — ასინქრონული მეთოდი, რომელიც int-ს აბრუნებს
async Task<int> PourTeaAsync()
{
    Console.WriteLine("ჩაის ჩამოსხმა...");
    await Task.Delay(1000);
    return 2;   // return-ში ჩვეულებრივ int-ს ვწერთ და C# მას თავად „ახვევს“ Task<int>-ში
}